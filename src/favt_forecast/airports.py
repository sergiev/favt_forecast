@dataclass(frozen=True)
class Airport:
    icao: str
    iata: str
    city: str
    name: str
    lat: float
    lon: float
    tz_offset: int
    cluster: str
    aliases: tuple[str, ...]

    @property
    def label(self) -> str:
        if self.name.casefold() == self.city.casefold():
            return self.city
        return f"{self.city}, {self.name}"

    def public(self) -> dict:
        return {
            "icao": self.icao,
            "iata": self.iata,
            "city": self.city,
            "name": self.name,
            "label": self.label,
            "lat": self.lat,
            "lon": self.lon,
            "tz_offset": self.tz_offset,
            "cluster": self.cluster,
            "cluster_label": CLUSTERS[self.cluster],
        }


